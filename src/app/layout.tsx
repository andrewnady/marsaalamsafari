import type { Metadata, Viewport } from 'next';
import { Jost, Manrope } from 'next/font/google';
import './globals.css';
import { siteConfig } from '@/config/site';
import { Header } from '@/components/layout/Header';
import { Footer } from '@/components/layout/Footer';
import { FloatingWhatsApp } from '@/components/layout/FloatingWhatsApp';
import { Analytics } from '@/components/analytics/Analytics';
import { WhatsAppClickTracker } from '@/components/analytics/WhatsAppClickTracker';
import { JsonLd } from '@/components/seo/JsonLd';
import { organizationSchema, websiteSchema } from '@/lib/seo/jsonld';

const jost = Jost({
  subsets: ['latin'],
  weight: ['400', '500', '600', '700'],
  variable: '--font-jost',
  display: 'swap',
});

const manrope = Manrope({
  subsets: ['latin'],
  weight: ['400', '500', '600', '700'],
  variable: '--font-manrope',
  display: 'swap',
});

export const viewport: Viewport = {
  themeColor: siteConfig.themeColor,
  width: 'device-width',
  initialScale: 1,
  colorScheme: 'light',
};

export const metadata: Metadata = {
  metadataBase: new URL(siteConfig.url),
  title: {
    default: `${siteConfig.name} | Premium Red Sea Tours & Excursions`,
    template: `%s | ${siteConfig.name}`,
  },
  description: siteConfig.description,
  applicationName: siteConfig.name,
  referrer: 'strict-origin-when-cross-origin',
  keywords: [
    'Marsa Alam safari',
    'Marsa Alam excursions',
    'Marsa Alam desert safari',
    'snorkeling Marsa Alam',
    'dolphin house tour',
    'Marsa Alam tours',
  ],
  authors: [{ name: siteConfig.legalName }],
  creator: siteConfig.legalName,
  publisher: siteConfig.legalName,
  formatDetection: { telephone: true, email: true, address: true },
  // Favicons/apple-icons are generated by app/icon.tsx and app/apple-icon.tsx.
  manifest: '/manifest.webmanifest',
  ...(siteConfig.verification.google && {
    verification: { google: siteConfig.verification.google },
  }),
  // No layout-level canonical: it would be inherited by every page that doesn't
  // set its own (e.g. 404s). Each page sets its canonical via buildMetadata.
};

export default function RootLayout({ children }: { children: React.ReactNode }) {
  return (
    <html lang="en" className={`${jost.variable} ${manrope.variable}`}>
      <body>
        <JsonLd schema={[organizationSchema(), websiteSchema()]} />
        <a href="#main" className="skip-link">Skip to content</a>
        <Header />
        <main id="main">{children}</main>
        <Footer />
        <FloatingWhatsApp />
        <Analytics />
        <WhatsAppClickTracker />
      </body>
    </html>
  );
}
